-- =====================================================================
-- 01_setup.sql : warehouse, database, role, S3 storage integration, stage
-- Replace <ACCOUNT_ID> and <BUCKET> before running.
-- =====================================================================
USE ROLE ACCOUNTADMIN;

-- Small, auto-suspending warehouse + a hard credit cap (cost control)
CREATE WAREHOUSE IF NOT EXISTS INGEST_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE RESOURCE MONITOR IF NOT EXISTS INGEST_RM
  WITH CREDIT_QUOTA = 5 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE INGEST_WH SET RESOURCE_MONITOR = INGEST_RM;

CREATE DATABASE IF NOT EXISTS INGEST_DB;
CREATE SCHEMA IF NOT EXISTS INGEST_DB.RAW;      -- landing tables, loaded by Snowpipe
CREATE SCHEMA IF NOT EXISTS INGEST_DB.CURATED;  -- cleaned, de-duplicated, MERGE-maintained
CREATE SCHEMA IF NOT EXISTS INGEST_DB.AUDIT;    -- reconciliation and monitoring views

-- Least-privilege role used by the pipeline objects
CREATE ROLE IF NOT EXISTS INGEST_ROLE;
GRANT USAGE, OPERATE ON WAREHOUSE INGEST_WH TO ROLE INGEST_ROLE;
GRANT ALL ON DATABASE INGEST_DB TO ROLE INGEST_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE INGEST_DB TO ROLE INGEST_ROLE;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE INGEST_ROLE;
GRANT ROLE INGEST_ROLE TO ROLE SYSADMIN;

-- Keyless access to S3: Snowflake assumes an IAM role, no access keys are stored anywhere
CREATE STORAGE INTEGRATION IF NOT EXISTS S3_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::<ACCOUNT_ID>:role/snowflake-s3-ingest-role'
  STORAGE_ALLOWED_LOCATIONS = ('s3://<BUCKET>/raw/');
GRANT USAGE ON INTEGRATION S3_INT TO ROLE INGEST_ROLE;

-- Copy STORAGE_AWS_IAM_USER_ARN and STORAGE_AWS_EXTERNAL_ID from this output into
-- aws/trust_policy_snowflake_role.json, then create/update the IAM role trust policy.
DESC INTEGRATION S3_INT;

USE ROLE INGEST_ROLE;
USE WAREHOUSE INGEST_WH;
USE DATABASE INGEST_DB;

CREATE FILE FORMAT IF NOT EXISTS RAW.FF_CSV_GZ
  TYPE = CSV
  COMPRESSION = GZIP
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'NULL')
  EMPTY_FIELD_AS_NULL = TRUE
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

CREATE STAGE IF NOT EXISTS RAW.S3_RAW_STAGE
  URL = 's3://<BUCKET>/raw/'
  STORAGE_INTEGRATION = S3_INT
  FILE_FORMAT = RAW.FF_CSV_GZ;

-- Smoke test (after the IAM trust policy is in place and a file has been uploaded)
LIST @RAW.S3_RAW_STAGE;
